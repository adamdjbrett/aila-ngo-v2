#!/usr/bin/env node
/**
 * Deduplicate src/assets/documents.
 *
 * The WordPress migration left every document at two paths: a flat
 * `documents/X.pdf` and a dated `documents/YYYY/MM/X.pdf`. The copies are
 * byte-identical, so the tree carries ~400 MB of redundancy that is re-copied
 * into `dist` on every build and uploaded to xmit twice on every deploy.
 *
 * This keeps one copy per unique file — preferring whichever path the site
 * actually links to — deletes the rest, and writes a redirect for every
 * dropped path so legacy and externally-cited URLs still resolve.
 *
 *   node scripts/dedup-documents.mjs --check    report only, exit 1 if work remains
 *   node scripts/dedup-documents.mjs            delete duplicates, rewrite redirects
 */

import {createHash} from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const docsDir = path.join(root, 'src/assets/documents');
const xmitToml = path.join(root, 'src/xmit.toml');
const urlPrefix = '/assets/documents/';

// Markers delimiting the generated redirect block inside src/xmit.toml, so the
// hand-written redirects above it are never touched.
const BEGIN = '# BEGIN dedup-documents redirects (generated by scripts/dedup-documents.mjs)';
const END = '# END dedup-documents redirects';

const checkOnly = process.argv.includes('--check');

/** Every file under src/assets/documents, as a path relative to that dir. */
function listDocuments() {
  const out = [];
  const walk = dir => {
    for (const entry of fs.readdirSync(dir, {withFileTypes: true})) {
      if (entry.name === '.DS_Store') continue;
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) walk(full);
      else if (entry.isFile()) out.push(path.relative(docsDir, full));
    }
  };
  walk(docsDir);
  return out.sort();
}

/**
 * Document paths linked from source content. Read from `src` rather than
 * `dist` so the script is correct without a prior build.
 */
function listReferenced() {
  const referenced = new Set();
  const pattern = /\/assets\/documents\/([A-Za-z0-9._%()'@+,\- ]+(?:\/[A-Za-z0-9._%()'@+,\- ]+)*\.[A-Za-z0-9]+)/g;
  const skip = new Set(['assets', 'node_modules', '_includes']);

  const walk = dir => {
    for (const entry of fs.readdirSync(dir, {withFileTypes: true})) {
      if (entry.name.startsWith('.') || skip.has(entry.name)) continue;
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) {
        walk(full);
      } else if (/\.(md|njk|webc|html|json|yaml|js)$/.test(entry.name)) {
        const text = fs.readFileSync(full, 'utf8');
        for (const match of text.matchAll(pattern)) {
          referenced.add(decodeURIComponent(match[1]));
        }
      }
    }
  };
  walk(path.join(root, 'src'));
  return referenced;
}

const hashFile = file => {
  const hash = createHash('sha256');
  hash.update(fs.readFileSync(file));
  return hash.digest('hex');
};

/**
 * Pick the copy to keep from a group of identical files. A referenced path
 * wins so no existing link has to change; otherwise prefer the flat path,
 * which is the one legacy WordPress URLs used.
 */
function chooseKeeper(paths, referenced) {
  const linked = paths.filter(p => referenced.has(p));
  if (linked.length > 0) return linked.sort((a, b) => a.length - b.length)[0];
  return [...paths].sort((a, b) => a.split('/').length - b.split('/').length || a.length - b.length)[0];
}

function tomlEscape(value) {
  return value.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
}

/** Escape a literal path for use inside an anchored xmit redirect regex. */
function regexEscape(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function writeRedirects(pairs) {
  const original = fs.readFileSync(xmitToml, 'utf8');
  const body = pairs
    .map(([from, to]) => {
      const fromPattern = `^${regexEscape(urlPrefix + from)}$`;
      return `[[redirects]]\nfrom = "${tomlEscape(fromPattern)}"\nto = "${tomlEscape(urlPrefix + to)}"\npermanent = true`;
    })
    .join('\n\n');

  const block = `${BEGIN}\n# ${pairs.length} duplicate paths collapsed; these keep legacy URLs resolving.\n\n${body}\n\n${END}`;

  const existing = new RegExp(`${regexEscape(BEGIN)}[\\s\\S]*?${regexEscape(END)}`);
  const next = existing.test(original)
    ? original.replace(existing, block)
    : `${original.trimEnd()}\n\n${block}\n`;

  fs.writeFileSync(xmitToml, next);
}

// ---------------------------------------------------------------------------

const files = listDocuments();
const referenced = listReferenced();

const groups = new Map();
for (const rel of files) {
  const digest = hashFile(path.join(docsDir, rel));
  if (!groups.has(digest)) groups.set(digest, []);
  groups.get(digest).push(rel);
}

const drops = [];
let freedBytes = 0;

for (const paths of groups.values()) {
  if (paths.length < 2) continue;
  const keeper = chooseKeeper(paths, referenced);
  for (const rel of paths) {
    if (rel === keeper) continue;
    // Never delete a path the site still links to.
    if (referenced.has(rel)) {
      console.warn(`  ! keeping ${rel} — still referenced alongside ${keeper}`);
      continue;
    }
    freedBytes += fs.statSync(path.join(docsDir, rel)).size;
    drops.push([rel, keeper]);
  }
}

drops.sort((a, b) => a[0].localeCompare(b[0]));

const missing = [...referenced].filter(rel => !files.includes(rel));
const mb = (freedBytes / 1024 / 1024).toFixed(1);

console.log(`documents:  ${files.length} files, ${groups.size} unique`);
console.log(`referenced: ${referenced.size} paths (${missing.length} pointing at files not on disk)`);
console.log(`duplicates: ${drops.length} redundant copies, ${mb} MB`);
if (missing.length) {
  console.log('\nreferenced but missing from disk (pre-existing broken links):');
  for (const rel of missing.sort()) console.log(`  - ${rel}`);
}

if (checkOnly) {
  if (drops.length > 0) {
    console.log('\nRun `npm run docs:dedup` to collapse them.');
    process.exit(1);
  }
  console.log('\nNo duplicates. Nothing to do.');
  process.exit(0);
}

if (drops.length === 0) {
  console.log('\nNo duplicates. Nothing to do.');
  process.exit(0);
}

for (const [rel] of drops) fs.rmSync(path.join(docsDir, rel));

// Remove directories the deletions left empty.
const pruneEmpty = dir => {
  for (const entry of fs.readdirSync(dir, {withFileTypes: true})) {
    if (entry.isDirectory()) pruneEmpty(path.join(dir, entry.name));
  }
  const remaining = fs.readdirSync(dir).filter(name => name !== '.DS_Store');
  if (remaining.length === 0 && dir !== docsDir) {
    fs.rmSync(dir, {recursive: true, force: true});
  }
};
pruneEmpty(docsDir);

writeRedirects(drops);

console.log(`\nRemoved ${drops.length} duplicates (${mb} MB).`);
console.log(`Wrote ${drops.length} redirects into src/xmit.toml.`);
